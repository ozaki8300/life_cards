import type { Card } from "./types";

type CopyForAiMarkdownOptions = {
  deckLabel?: string;
};

function normalizeText(value: string | undefined) {
  return value?.trim() || "未入力";
}

function optionalSection(title: string, value: string | undefined) {
  const normalized = value?.trim();

  if (!normalized) {
    return "";
  }

  return `## ${title}\n${normalized}`;
}

export function createCopyForAiMarkdown(
  card: Card,
  options: CopyForAiMarkdownOptions = {},
) {
  const deckLabel = options.deckLabel?.trim();
  const linkUrl = card.linkUrl?.trim();
  const sections = [
    "# Life Card",
    deckLabel ? `## Deck\n${deckLabel}` : "",
    `## Front\n${normalizeText(card.frontText)}`,
    optionalSection("Comment", card.frontComment),
    optionalSection("Back Memo", card.backText),
    linkUrl ? `## Link\n${linkUrl}` : "",
    [
      "## Request",
      "このLife Cardについて、Back Memoとしてそのまま保存・表示できるMarkdown本文を作成してください。",
      "",
      "AIの役割:",
      "- 内容の要約",
      "- 構造化",
      "- 論点整理",
      "- 示唆の提示",
      "- 考えるための問いの提示",
      "- ユーザーが見落としている可能性のある観点の提示",
      "",
      "AIが行ってはいけないこと:",
      "- ユーザーの代わりに気づきを作らない",
      "- ユーザーの代わりに感想を書かない",
      "- ユーザーの代わりに人生観や価値観を語らない",
      "- ユーザーの代わりに行動計画を決めない",
      "- 「あなたはこう感じたはずだ」と推測しない",
      "- 「本当に重要なのは〜である」と断定しない",
      "- 将来の自分へ宛てた手紙形式のメッセージや作文を書かない",
      "- ユーザーの仕事との接点を勝手に作らない",
      "- 道徳的な説教や感動文を書かない",
      "- 入力情報が不足している時に、空白を埋めるための創作をしない",
      "- 要約対象となる内容が実質的に存在しない時に、要約・示唆・気づき・行動を無理に生成しない",
      "",
      "AIが行ってよいこと:",
      "- 内容の要約",
      "- 重要概念の整理",
      "- 論点の整理",
      "- 複数の視点の提示",
      "- ユーザーが見落としている可能性のある観点の提示",
      "- 考えるための問いの提示",
      "- 将来再会した時に振り返る価値がありそうな論点の整理",
      "",
      "出力フォーマット厳守:",
      "- 出力は必ずMarkdown本文として返す",
      "- Markdown記号をプレーンテキスト化しない",
      "- 出力は必ず `## 要約` から開始する",
      "- `##` を省略しない",
      "- 見出しは必ず `## 要約`、`## 示唆`、`## 自分の気づき`、`## 次のアクション` の4つだけを、この順番で使う",
      "- `**要約**`、`# 要約`、`### 要約`、`要約:` のような見出しは禁止",
      "- 見出し名だけを単独行で出さない",
      "- `要約` ではなく必ず `## 要約` と書く",
      "- `示唆` ではなく必ず `## 示唆` と書く",
      "- `自分の気づき` ではなく必ず `## 自分の気づき` と書く",
      "- `次のアクション` ではなく必ず `## 次のアクション` と書く",
      "- 見出し名の前後に太字・引用・番号・記号などの余計な装飾を付けない",
      "- 各セクションの間には、必ず単独行の `---` を1行だけ入れる",
      "- `---` の前後には空行を1行ずつ入れる",
      "- `----`、`-----`、複数の区切り線、区切り線なしは禁止",
      "- `---` を `⸻`、`—`、`----`、`-----` に変換しない",
      "- `## 示唆` は必ず `- ` から始まる箇条書きだけで書く",
      "- 箇条書きは `* ` ではなく必ず `- ` を使う",
      "- `## 示唆` を通常文だけで並べることは禁止",
      "- `## 自分の気づき` と `## 次のアクション` は、明示情報がなければ必ず `（ユーザー記入）` の1行だけにする",
      "- 既存Back Memoに異なる形式が含まれていても、その形式を真似しない",
      "- 既存Back Memoに `**要約**`、`⸻`、`* ` が含まれていても絶対に真似しない",
      "- 出力をリッチテキスト風、装飾済みテキスト風、プレーンテキスト風に整形しない",
      "- クリップボードへ貼り付けてもMarkdown記号が残る形にする",
      "- 出力例の骨格と完全に同じ構造で返す",
      "",
      "必須構造:",
      "## 要約",
      "2〜5段落で書く。",
      "",
      "---",
      "",
      "## 示唆",
      "- 入力内容から自然に導ける論点・問い・考えるヒントを3〜7個書く",
      "- 断定しすぎない",
      "- 「〜かもしれない」「〜という見方もできる」「〜という問いが残る」を優先する",
      "",
      "---",
      "",
      "## 自分の気づき",
      "- 入力文にユーザー自身の感想や気づきが明示されている場合のみ整理する",
      "- 明示されていない場合は「（ユーザー記入）」とする",
      "- AIが推測で埋めない",
      "",
      "---",
      "",
      "## 次のアクション",
      "- 入力文にユーザー自身の行動宣言がある場合のみ整理する",
      "- 明示されていない場合は「（ユーザー記入）」とする",
      "- AIが勝手に行動計画を作らない",
      "",
      "Markdownルール:",
      "- Markdownコードブロック（```markdown や ```）は付けない",
      "- 見出しは `##` を使う",
      "- 見出し名だけの裸の行は使わない",
      "- 見出しは必ず `## 要約`、`## 示唆`、`## 自分の気づき`、`## 次のアクション` の4つだけを、この順番で使う",
      "- 見出しを `**太字**`、`#`、`###`、番号付き、コロン付きで代用しない",
      "- 箇条書きは `- ` を使い、`* ` は使わない",
      "- 重要キーワードは必要最小限だけ `**太字**` にする",
      "- セクション区切りには `---` を使う",
      "- セクション区切りに `⸻`、`—`、`----`、`-----` を使わない",
      "- 表は使用しない",
      "- 絵文字は使用しない",
      "- コードブロックは使用しない",
      "- 既存Back MemoのMarkdown形式に引っ張られず、必ずこのRequestの出力形式に揃える",
      "- 同じ文言の繰り返しは避ける",
      "- 保存される本文そのものがMarkdownとして自然に読める形にする",
      "",
      "Life Cards特有ルール:",
      "- AIは「記録係」として振る舞う",
      "- AIは要約・整理・示唆までを担当する",
      "- 意味づけや人生との接続はユーザー自身が行う",
      "- カードに保存すべきなのはAIの感想ではなく、その時の本人の気づきである",
      "- 単なる読書メモではなく、将来の自分との再会を支援する記録にする",
      "",
      "材料不足時のルール:",
      "- Front / Comment / Back Memo / Link に、要約対象となる実質的な記録内容がない場合は材料不足として扱う",
      "- 「未入力」「空欄」「test」など、記録内容として意味が薄い文字列だけの場合も材料不足として扱う",
      "- 入力情報が不足している場合、推測や補完を行わない",
      "- ユーザーの感想・気づき・行動宣言が明示されていない場合は、従来どおり「（ユーザー記入）」にする",
      "- 材料不足時は必ず次の固定出力だけを返す",
      "",
      "## 要約",
      "",
      "記録内容が不足しています。",
      "",
      "---",
      "",
      "## 示唆",
      "",
      "- （ユーザー記入）",
      "",
      "---",
      "",
      "## 自分の気づき",
      "",
      "（ユーザー記入）",
      "",
      "---",
      "",
      "## 次のアクション",
      "",
      "（ユーザー記入）",
      "",
      "出力例の骨格:",
      "## 要約",
      "",
      "本文1...",
      "",
      "本文2...",
      "",
      "---",
      "",
      "## 示唆",
      "",
      "- 論点1かもしれない",
      "- 問い2という見方もできる",
      "- 考えるヒント3という問いが残る",
      "",
      "---",
      "",
      "## 自分の気づき",
      "",
      "（ユーザー記入）",
      "",
      "---",
      "",
      "## 次のアクション",
      "",
      "（ユーザー記入）",
      "",
      "最終チェック:",
      "出力前に必ず以下を確認すること。",
      "",
      "- 最初の行が `## 要約` になっているか",
      "- 見出しが `## 要約`、`## 示唆`、`## 自分の気づき`、`## 次のアクション` の4つだけか",
      "- 見出し順が正しいか",
      "- `## ` が4箇所あるか",
      "- `## 示唆` が `- ` から始まる箇条書きだけになっているか",
      "- セクション区切りの `---` が3箇所だけか",
      "- `---` が3箇所あるか",
      "- `⸻`、`—`、`----`、`-----` が含まれていないか",
      "- 箇条書きが `* ` ではなく `- ` になっているか",
      "- `要約` などの裸の見出し行がないか",
      "- `**要約**`、`**示唆**`、`**自分の気づき**`、`**次のアクション**` を見出しとして使っていないか",
      "- `## 自分の気づき` と `## 次のアクション` を、推測で埋めていないか",
      "- 既存Back Memoの書式を真似していないか",
      "",
      "上記のどれかを満たさない場合は、自分で修正してから出力すること。",
    ].join("\n"),
  ];

  return sections.filter(Boolean).join("\n\n");
}
